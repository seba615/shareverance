
-- ============================================================
-- Shareverance - Modelo inicial de datos del MVP
-- Migracion Flyway: V2
-- ============================================================

-- 1. Usuarios de la aplicacion
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Organizaciones
CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(50) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'ARS',
    timezone VARCHAR(100) NOT NULL
        DEFAULT 'America/Argentina/Buenos_Aires',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. Membresias: relacion entre usuarios y organizaciones
CREATE TABLE user_organization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_membership_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_membership_organization
        FOREIGN KEY (organization_id) REFERENCES organizations(id),

    CONSTRAINT uq_membership_user_organization
        UNIQUE (organization_id, user_id),

    CONSTRAINT uq_membership_organization_id
        UNIQUE (organization_id, id),

    CONSTRAINT ck_membership_role
        CHECK (role IN ('ADMIN', 'USER'))
);

-- 4. Categorias de gastos
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    color VARCHAR(7),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_category_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id),

    CONSTRAINT uq_category_organization_id
        UNIQUE (organization_id, id),

    CONSTRAINT uq_category_name_per_organization
        UNIQUE (organization_id, name),

    CONSTRAINT ck_category_color
        CHECK (color IS NULL OR color ~ '^#[0-9A-Fa-f]{6}$')
);

-- 5. Gastos
CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,
    expense_date DATE NOT NULL,
    description VARCHAR(500) NOT NULL,
    receipt_url VARCHAR(2048),
    split_type VARCHAR(20) NOT NULL DEFAULT 'EQUAL',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_expense_creator_membership
        FOREIGN KEY (organization_id, created_by_user_id)
        REFERENCES user_organization(organization_id, user_id),

    CONSTRAINT fk_expense_category
        FOREIGN KEY (organization_id, category_id)
        REFERENCES categories(organization_id, id),

    CONSTRAINT uq_expense_organization_id
        UNIQUE (organization_id, id),

    CONSTRAINT ck_expense_amount
        CHECK (amount > 0),

    CONSTRAINT ck_expense_split_type
        CHECK (split_type IN ('EQUAL', 'INDIVIDUAL'))
);

-- 6. Distribucion de los gastos entre miembros
CREATE TABLE expense_splits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    expense_id BIGINT NOT NULL,
    user_organization_id BIGINT NOT NULL,
    amount DECIMAL(12, 2) NOT NULL,

    CONSTRAINT fk_split_expense
        FOREIGN KEY (organization_id, expense_id)
        REFERENCES expenses(organization_id, id),

    CONSTRAINT fk_split_membership
        FOREIGN KEY (organization_id, user_organization_id)
        REFERENCES user_organization(organization_id, id),

    CONSTRAINT uq_split_expense_member
        UNIQUE (expense_id, user_organization_id),

    CONSTRAINT ck_split_amount
        CHECK (amount > 0)
);
